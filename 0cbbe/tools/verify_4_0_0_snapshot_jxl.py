from __future__ import annotations
from pathlib import Path
import argparse, hashlib, json, re, sqlite3

parser=argparse.ArgumentParser(description='Verify 4.0.0 durable snapshot and all-JXL browser asset contract')
parser.add_argument('--root',type=Path,default=Path(__file__).resolve().parents[1])
args=parser.parse_args();root=args.root.resolve()
def content(path):return (root/path).read_text(encoding='utf-8')
def need(condition,message):
    if not condition:raise SystemExit('FAIL '+message)

manifest=json.loads(content('tools/jxl_asset_manifest.json'))
rows=manifest.get('assets',[])
need(len(rows)==manifest.get('assetCount')==284,'unexpected JPEG XL asset count')
need(len({r['to'] for r in rows})==len(rows),'duplicate JPEG XL targets')
need(sum('country-flags/' in r['from'] for r in rows)==250,'country flag census mismatch')
for r in rows:
    src=r['from'];target=r['to'];asset=root/target
    need(not (root/src).exists(),f'obsolete image still present: {src}')
    need(src.endswith(('.png','.ico','.svg','.webp')) and target.endswith('.jxl'),f'image migration is incomplete: {src}')
    need(asset.is_file(),f'JPEG XL asset missing: {target}')
    raw=asset.read_bytes()
    need(len(raw)==r['jxlBytes'] and hashlib.sha256(raw).hexdigest()==r['jxlSha256'],f'JPEG XL asset digest mismatch: {target}')
    need(raw[:2]==b'\xff\x0a' or raw[4:12]==b'JXL \r\n\x87\n',f'JPEG XL signature mismatch: {target}')
    need(r['width']>0 and r['height']>0,'invalid JPEG XL dimensions')
    need(r['distance']==0 if 'country-flags/' in src else r['distance']<=0.15,'excessive JPEG XL distance')
    need(r['rgbMAE']<=0.8 and r['rgbMaxDelta']<=25,'JPEG XL decoded quality gate violated')
for f in (root/'assets').rglob('*'):
    if f.is_file():need(f.suffix.lower() not in ('.png','.svg','.webp','.ico','.jpg','.jpeg'),f'legacy image in release: {f.relative_to(root)}')
probe=(root/'assets/jxl-probe.v4000.jxl').read_bytes()
need(probe[:2]==b'\xff\x0a' or probe[4:12]==b'JXL \r\n\x87\n','first-party JPEG XL browser probe invalid')

app=content('assets/app.v4000.js');index=content('index.html');css=content('assets/site.v4000.css');compat=content('assets/browser-compat.v4000.js');worker=content('worker/src/index.js');wr=json.loads(content('worker/wrangler.jsonc'));rules=content('rules/PROJECT_RULES.md')
need("const DATABASE_VERSION='4.0.0'" in app and 'assets/app.v4000.js?v=4000' in index,'frontend release identity mismatch')
need('VulkanScope Database <strong>4.0.0</strong>' in index,'footer version missing')
need('jxl-unsupported.html' in compat and (root/'jxl-unsupported.html').is_file(),'JPEG XL error page not connected')
need('new Image()' in compat and '.naturalWidth===2' in compat and 'jxlProbe()' in compat,'native JPEG XL decoder check missing')
need("'incorrect_mime'" in compat and "'probe_unavailable'" in compat,'JPEG XL MIME/network failure discrimination missing')
need("window.__VULKANSCOPE_COMPATIBLE__=true" in compat and 'launchApp();' in compat,'JPEG XL support must gate application execution')
need('document.createElement(\'script\')' in compat and 'app.v4000.js?v=4000' in compat,'deferred app boot missing')
need('<script src="./assets/app.v4000.js' not in index,'application executes before native JPEG XL verification')
for name,value in [('app.v4000.js',app),('site.v4000.css',css),('index.html',index),('browser-compat.v4000.js',compat)]:
    need(not re.search(r'\.(?:png|svg|ico|webp|jpeg|jpg)(?:["\'`?/#]|$)',value),f'obsolete image URL in {name}')
need('## Release 1.4.13 durable snapshot reconciliation and native JPEG XL requirements' in rules and '## Release 4.0.0 Windows build-artifact hygiene and 1.4.13 compatibility requirements' in rules,'new rules contract not appended')
need('0004_snapshot_reconciliation.sql' in ','.join(x.name for x in (root/'worker/migrations').glob('*.sql')),'D1 migration missing')
need('snapshotIntent(env,id,now)' in worker and 'env.DB.batch(statements)' in worker,'D1 report+snapshot intent not atomic')
need('ctx.waitUntil(triggerQueuedSnapshot(env,id,submittedAt)' in worker,'nonblocking immediate dispatch missing')
need('async scheduled(controller,env,ctx)' in worker and 'reconcileSnapshot(env)' in worker,'Cron reconciliation missing')
need('snapshotManifestMatches' in worker and 'manifest.reportCount===liveCount' in worker,'Pages snapshot publication not checked against D1')
need("url.pathname==='/v1/snapshot-status'" in worker,'snapshot status endpoint missing')
need(wr.get('triggers',{}).get('crons')==['*/5 * * * *'],'five-minute Cloudflare Cron missing')
need(wr.get('vars',{}).get('SNAPSHOT_PUBLIC_MANIFEST_URL','').startswith('https://'),'public snapshot manifest URL missing')
need('SNAPSHOT_GITHUB_TOKEN' not in wr.get('vars',{}),'GitHub token must remain a Cloudflare secret')
need('SNAPSHOT_GITHUB_TOKEN' in worker and "last_error_code='dispatch_failed'" in worker,'retry/error bookkeeping missing')
con=sqlite3.connect(':memory:')
for file in sorted((root/'worker/migrations').glob('*.sql')):con.executescript(file.read_text(encoding='utf-8'))
need(con.execute("SELECT COUNT(*) FROM snapshot_refresh_control WHERE id=1").fetchone()[0]==1,'snapshot state migration does not seed singleton')
con.execute("INSERT INTO reports(id,submitted_at,schema_version,gpu_name,vendor_id,device_id,driver_mode,driver_version,device_api_version,manufacturer,model,payload_json) VALUES ('x','2026-10-23T19:00:00Z',2,'GPU','1','2','driver','1','1','manufacturer','model','{}')")
con.execute("INSERT INTO snapshot_refresh_control(id,queued_report_id,queued_at) SELECT 1,id,submitted_at FROM reports WHERE id='x' ON CONFLICT(id) DO UPDATE SET queued_report_id=excluded.queued_report_id,queued_at=excluded.queued_at WHERE excluded.queued_at>=COALESCE(snapshot_refresh_control.queued_at,'')")
need(con.execute('SELECT queued_report_id FROM snapshot_refresh_control').fetchone()[0]=='x','D1 intent UPSERT failed')
need('"databaseVersion":"4.0.0"' in content('tools/build_index.py'),'static index builder release identity mismatch')
need('tools/jxl_asset_manifest.json' in content('tools/build_pages_artifact.py'),'Pages build does not enforce inventory')
need("glob('*.jxl')" in content('tools/build_pages_artifact.py'),'Pages build not using JPEG XL country flags')
need('jxl-unsupported.html' in content('tools/build_pages_artifact.py'),'Pages error page not staged')
print('PASS VulkanScope Database 4.0.0: D1 durable snapshot/cron + native JPEG XL gate + 284 integrity-verified JXL assets')
